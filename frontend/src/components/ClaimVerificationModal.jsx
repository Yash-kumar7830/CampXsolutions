"use client";
import React, { useState } from 'react';
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle, DialogTrigger } from '@/components/ui/dialog';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { verifyClaim } from '@/lib/verification';
// Removed: import { QRCode } from 'qrcode.react'; 
import { CheckCircle, XCircle } from 'lucide-react';
import { showSuccess, showError } from '@/utils/toast';
import { useAuth } from '@/contexts/AuthContext'; // Import useAuth
const ClaimVerificationModal = ({ item, children }) => {
    const [isOpen, setIsOpen] = useState(false);
    const [loserAnswer, setLoserAnswer] = useState('');
    const [verificationResult, setVerificationResult] = useState(null);
    const [claimToken, setClaimToken] = useState(null);
    const { currentUser } = useAuth(); // Use auth context
    const handleVerify = () => {
        if (!currentUser) {
            showError("You must be logged in to claim an item.");
            return;
        }
        if (!loserAnswer.trim()) {
            showError("Please enter your answer to verify the claim.");
            return;
        }
        const result = verifyClaim(loserAnswer, item.hidden_detail);
        setVerificationResult(result);
        if (result.isMatch) {
            // In a real application, this claimToken would be generated by the backend
            // and would contain secure, unique identifiers for the claim.
            const generatedToken = `CLAIM-${item.id}-${Date.now()}`;
            setClaimToken(generatedToken);
            showSuccess("Claim verified! Here is your return ID.");
            // Save the claim to localStorage
            const newClaim = {
                report_id: item.id,
                claimant_id: currentUser.id,
                answer_text: loserAnswer,
                match_score: result.score,
                status: 'pending', // Initial status, would be 'approved' by admin later
                claimed_at: new Date().toISOString(),
            };
            const storedClaims = JSON.parse(localStorage.getItem('allFindItClaims') || '[]');
            localStorage.setItem('allFindItClaims', JSON.stringify([...storedClaims, newClaim]));
            // Optionally update item status to 'matching'
            const storedItems = JSON.parse(localStorage.getItem('allFindItItems') || '[]');
            const updatedItems = storedItems.map((i) => i.id === item.id ? { ...i, status: 'matching' } : i);
            localStorage.setItem('allFindItItems', JSON.stringify(updatedItems));
        }
        else {
            showError("Claim could not be verified. Please try again.");
        }
    };
    const handleClose = () => {
        setIsOpen(false);
        setLoserAnswer('');
        setVerificationResult(null);
        setClaimToken(null);
    };
    return (<Dialog open={isOpen} onOpenChange={setIsOpen}>
      <DialogTrigger asChild>{children}</DialogTrigger>
      <DialogContent className="sm:max-w-[425px]">
        <DialogHeader>
          <DialogTitle>Claim Item: {item.title}</DialogTitle>
          <DialogDescription>
            To claim this item, please provide the hidden detail known only by the true owner.
          </DialogDescription>
        </DialogHeader>
        <div className="grid gap-4 py-4">
          {!claimToken ? (<>
              <div className="grid grid-cols-4 items-center gap-4">
                <Label htmlFor="loserAnswer" className="text-right">
                  Your Answer
                </Label>
                <Input id="loserAnswer" value={loserAnswer} onChange={(e) => setLoserAnswer(e.target.value)} className="col-span-3" placeholder="e.g., 'red keychain with a cat'"/>
              </div>
              {verificationResult && (<div className={`text-center text-sm ${verificationResult.isMatch ? 'text-green-600' : 'text-red-600'} flex items-center justify-center gap-2`}>
                  {verificationResult.isMatch ? <CheckCircle className="h-4 w-4"/> : <XCircle className="h-4 w-4"/>}
                  {verificationResult.isMatch ? 'Match successful!' : `No match. Score: ${(verificationResult.score * 100).toFixed(0)}%`}
                </div>)}
              <Button onClick={handleVerify} className="w-full mt-2" disabled={!currentUser}>
                {currentUser ? "Verify Claim" : "Login to Verify Claim"}
              </Button>
            </>) : (<div className="flex flex-col items-center gap-4">
              <p className="text-lg font-semibold text-green-600 flex items-center gap-2">
                <CheckCircle className="h-5 w-5"/> Claim Approved!
              </p>
              <p className="text-sm text-muted-foreground text-center">
                Show this Claim ID to an admin to confirm your return.
              </p>
              <div className="p-4 border border-border rounded-lg bg-white dark:bg-gray-800">
                <p className="text-xl font-bold text-primary">{claimToken}</p>
              </div>
              <p className="text-xs text-muted-foreground break-all text-center">
                Claim ID: {claimToken}
              </p>
              <Button onClick={handleClose} className="w-full mt-2">
                Close
              </Button>
            </div>)}
        </div>
      </DialogContent>
    </Dialog>);
};
export default ClaimVerificationModal;
